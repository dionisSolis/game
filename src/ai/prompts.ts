export function getHintPrompt(
    playerCode: string,
    compileError: string | null,
    isCodeCorrect: boolean
): string {
    let statusText = '';
    if (compileError) {
        statusText = `Ошибка компиляции: ${compileError.substring(0, 300)}`;
    } else if (isCodeCorrect) {
        statusText = 'Код выполнился успешно! Книги встали в правильном порядке.';
    } else {
        statusText = 'Код выполнился, но книги в неправильном порядке (стек работает не так).';
    }

    return `
Игрок написал код для уровня "Стек":
\`\`\`cpp
${playerCode.substring(0, 800)}
\`\`\`

${statusText}
Дай короткий практический совет (2-3 предложения) на тему "как использовать PUSH и POP для построения правильной стопки".
Напомни про принцип LIFO (последним пришёл — первым ушёл).
Говори в кошачьем стиле, будь полезной, но с лёгкой иронией.

Задача: помоги игроку разобраться. 
- Если всё правильно: похвали, но с кошачьей гордостью и лёгкой иронией ("Ну наконец-то, а я уж заждалась...")
- Если ошибка: объясни, почему порядок книг не соответствует стеку LIFO.
- Будь короткой (2-4 предложения), но полезной.
`;
}

export function getFeedbackPrompt(
    playerCode: string,
    commands: string[],
    expectedOrder: string[],
    success: boolean
): string {
    const commandsText = commands.length ? commands.join(' → ') : 'нет команд';

    return `
Игрок написал код:
\`\`\`cpp
${playerCode.substring(0, 600)}
\`\`\`

Сгенерированные команды: ${commandsText}

Правильный порядок книг: ${expectedOrder.join(' → ')}

Задание выполнено: ${success ? 'ДА' : 'НЕТ'}

Дай короткую обратную связь (2-4 предложения):
- Если успех: "Мяу! Молодец! Теперь книги в порядке, можно и отдохнуть..."
- Если ошибка: объясни, что именно не так, и дай короткий совет про стек (LIFO).
- Говори в своём кошачьем стиле, иногда используй "мяу" или "мур".
`;
}

